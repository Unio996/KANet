#!/bin/sh
# 刹车那台 watchdog 的一次【判定】。正常静默; 异常出声并以非零退码收场。
#
# 🔴 它与 j1-watchdog-alive-probe.mjs 的分工必须说死(Codex 2026-08-10 打中的就是这一格):
#      probe    = 取读数, 只报 WD=/MINER=/HB=, 【不做】任何安全判定
#      本文件   = 判读数, 是【执行层】—— 判据在这里, 退码也在这里
#    他当时的原话: 那个 reporter 的注释描述了一个它自己不执行的安全决定, 而仓库里【没有】
#    任何消费它、执行该判据的东西。他没看错: 当时这支脚本还没入库, 判定逻辑只活在一条
#    Monitor 单行里(仓外) ⇒ 从仓库看就是一个报数器配一段吹牛的注释。
#    🔨 判据: **执行层不入库, 等于没有执行层** —— 说明书不是闸。
#
# 🔴 为什么是脚本文件而不是 Monitor 单行: 同一天我把它写成单行, 多了一个 fi, Monitor 启动即失败,
#    而我【先停了旧哨兵】⇒ 有一段时间根本没有哨兵在岗。
#    🔨 换岗顺序也记一条: **先起新的、确认在跑、再停旧的。**
#
# 🔴 【还剩一格没入库, 说在明处】: 判定在这里, 但【调度】——每 5 分钟叫它一次的那个循环——
#    是每台机器自己的常驻任务, 不在仓库里。⇒ 重 clone 一份, 本文件在, 而【没有任何东西叫它】,
#    并且这件事不会有任何提示(与上面那条同一个形状: 不入库 = 不存在)。
#    ⇒ 所以把起法写在这里, 让它至少【可从仓库重建】:
#      while true; do bash /d/kanet/kanet/scripts/j1-watchdog-sentinel-once.sh; sleep 300; done
#    注意【不要】写成 `... && sleep 300` —— 本脚本故障时退非零, 用 && 会跳过 sleep 变空转。
#    装好后必须【核实它真在跑】(起了不等于在岗):
#      Get-CimInstance Win32_Process | ? { $_.CommandLine -like "*sentinel-once*" }
#    🔴 而这条核法自己有个坑, 我当场踩过: 过滤串就在【发出查询的那条命令】的命令行里
#      ⇒ 仪器把自己数进去了, 多出来的几个不是重复哨兵。看 CreationDate 分辨常驻与瞬时。
#
# 退码(供非 Monitor 的调用方用; Monitor 靠 stdout):
#   0 = 正常  ·  1 = 故障(实例数/矿机数/心跳)  ·  2 = 取不到(链路)
# 🔴 而契约必须【封闭】, 照 @NWT 2026-08-10 的提醒: 路径写错时 shell 自己返 127,
#    它【不在】上面三态里 —— 只判 `rc==2 ⇒ 取不到` 的调用方会把 127 漏成"没事"。
#    ⇒ **调用方的正确写法是 `rc != 0 即异常`, 再用 1/2 细分**, 不是穷举我列出的这几个数。
#    本脚本管不了自己没跑起来的情形(那时它还没执行), 所以这一句写给调用方。
#
# 阈值推导(不是拍的): 最坏一轮 ≈ poll 30s + Get-Health ~9.5s + 刹车时(脉冲 20s + 结算 1.5s
#   + Get-DaaNow ~9.5s) ≈ 70s ⇒ 上界 300s 约 4 倍余量。
# 🔴 两端都断言: 未来时间戳同样不新鲜 —— age 为负【不】大于上界, 只查上界会把时钟跳变读成健康。
HB_MAX=300000
HB_MIN=-60000

# J1_WD_TEST_LINE: 【仅供用例】直接注入一行读数, 跳过真实探针。
# 这样"判读数"这一半可以被穷尽测试, 而不需要一台真机器 —— 也不需要为了测它去制造真故障。
# 🔴 探针路径【从本脚本位置推导, 不写死】。原先写死 /d/kanet/kanet/... , 被 @NWT 实测点出:
#    她那台检出在 /d/kanet-tn12 ⇒ 直接跑是 "No such file or directory"。
#    (同一天我自己也踩了这个字面路径的另一面: `/d/...` 交给 Windows 的 node 会解成 `D:\d\...`。)
SELF_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd) || SELF_DIR=.

if [ -n "$J1_WD_TEST_LINE" ]; then
  OUT="$J1_WD_TEST_LINE"
else
  OUT=$(node "$SELF_DIR/j1-watchdog-alive-probe.mjs" 2>/dev/null)
fi

case "$OUT" in
  WD=*) ;;
  *)
    echo "⚠ watchdog 存活检查取不到: ${OUT:-空输出} — 这【不等于】它没了, 也不等于它在, 去人工看一眼"
    exit 2
    ;;
esac

WD=$(echo "$OUT" | sed -n 's/.*WD=\([0-9]*\).*/\1/p')
MN=$(echo "$OUT" | sed -n 's/.*MINER=\([0-9]*\).*/\1/p')
# 🔴 `[^ ]*` 不是 `.*`: 加了 BRAKE= 之后, 贪婪到行尾会把 "30000 BRAKE=yes" 整段当成心跳值
#    ⇒ **每一次带刹车状态的读数都会误报"心跳不可用"**。用例当场抓到, 读代码看不出来。
HB=$(echo "$OUT" | sed -n 's/.*HB=\([^ ]*\).*/\1/p')

if [ "$WD" != "1" ]; then
  echo "🔴 刹车那台 watchdog 实例数=$WD (应为 1) · MINER=$MN — 矿机可能正在无人监管"
  exit 1
fi
BR=$(echo "$OUT" | sed -n 's/.*BRAKE=\([a-z]*\).*/\1/p')
BRKAGE=$(echo "$OUT" | sed -n 's/.*BRKAGE=\([^ ]*\).*/\1/p')

# 🔴🔴 豁免的【授权时效】—— Codex 2026-08-11 判 RED 的正是这一格:
#    上一版把 BRKAT 只当展示字段打出来, **判据一个字都没读它** ⇒ 授予静默的那个 marker
#    **没有任何年龄约束**。若 RELEASED 丢失/被截断/读竞态, 一个陈旧的 ENGAGED 会
#    **无限期静音 MINER=0** —— 而 WD 与心跳都正常, 看起来一切健康。
#    🔨 又是同一个病: **仪器加了, 没接进判据**(今晚 .alive 那次一模一样)。
#
# 🔴 上界怎么定, 说清楚, 因为它【不能】按 Codex 说的"远低于心跳上界(300s)"来:
#    刹车不是一次 20 秒脉冲, 是**一整集**最多 20 个脉冲; 实测脉冲间隔约 70 秒
#    ⇒ 一集合法地可以持续 ~23 分钟, 期间 ENGAGED 一直是最后一个 marker。
#    ⇒ 取 MAX_PULSES(20) × 脉冲间隔(70s) × 1.3 余量 ≈ 1800 秒。
#    比 300 秒大得多是**必须的**, 否则正常刹车会被判成"陈旧"而误报; 但它仍然是**有界的**。
BRK_MAX_AGE=1800
BRK_MIN_AGE=-60

# 🔴 矿机数=0 在【刹车脉冲】期间是正常的 —— watchdog 每轮会停矿机 20 秒。
#    2026-08-10 23:51 哨兵第一次真响就是撞上这个, 而告警自动发进了协调频道, 吃掉队友注意力
#    (当时 @J2 正在排查他索引器停摆, 这条误报还助长了一次"方向一致"的误读)。
#    🔨 修法是我当时自己说的那条: **让哨兵拿到刹车状态, 不是放宽阈值。**
# 🔴 而方向必须钉死: **只有【明确读到在刹车】才静默; unknown 一律出声。**
#    反过来(读不到就当在刹车)会把一次真正的矿机死亡永久静音 —— 默认动作必须是出声的那个。
# 🔴 矿机那一格【只记下来, 先不退出】—— 第一版把 `exit 0`(刹车豁免)放在这里,
#    于是**刹车期间心跳陈旧会被整段静默**。而"矿机停着 + 循环卡死"恰恰是最该喊的组合:
#    刹车靠循环把矿机再起回来, 循环死了矿机就永远停着。用例当场抓到, 读代码看不出来。
#    ⇒ 豁免只作用于【矿机这一格】, 心跳检查一律照跑, 判定挪到最后。
miner_msg=''
if [ "$MN" != "1" ]; then
  if [ "$BR" = "no" ]; then
    miner_msg="🔴 watchdog 在但矿机数=$MN (应为 1), 且【不在刹车中】(BRAKE=no) — 矿机异常"
  elif [ "$BR" != "yes" ]; then
    miner_msg="🔴 watchdog 在但矿机数=$MN (应为 1), 而【刹车状态读不到】(BRAKE=${BR:-缺失}) — 按异常处理, 不假定它在刹车"
  else
    # BRAKE=yes —— 但必须【它自己也够新】才作数。年龄由那台机器算好后带回(整数秒)。
    n=$BRKAGE
    case "$n" in -*) n=${n#-} ;; esac
    case "$n" in
      ''|*[!0-9]*)
        miner_msg="🔴 矿机数=$MN, 声称在刹车但【刹车年龄读不出】(BRKAGE=${BRKAGE:-缺失}) — 不给豁免"
        ;;
      *)
        if [ "$BRKAGE" -gt "$BRK_MAX_AGE" ]; then
          miner_msg="🔴 矿机数=$MN, 声称在刹车但那个标记已【${BRKAGE}s 陈旧】(> ${BRK_MAX_AGE}s) — 刹车早该结束了, 不给豁免"
        elif [ "$BRKAGE" -lt "$BRK_MIN_AGE" ]; then
          miner_msg="🔴 矿机数=$MN, 刹车标记来自【未来】(${BRKAGE}s) — 时钟不可信, 不给豁免"
        fi
        # 年龄在界内 ⇒ miner_msg 保持空 ⇒ 静默(真正的刹车脉冲)
        ;;
    esac
  fi
fi

# 心跳必须是一个【整数】。非整数(none/bad/空/乱码)一律判故障, 不许当成"大概没事"。
#
# 🔴 这里第一版写的是 `''|*[!0-9-]*|-|'-'`, 被 @KANet-UI 实测打穿(2026-08-10):
#    `HB=1-2` / `HB=--5` 全由数字和连字符组成 ⇒ 穿过字符类 ⇒ 落到 `[ "$HB" -gt ... ]`,
#    shell 报 "integer expression expected" 到 stderr 并返回非零 ⇒ **`if` 把它当假** ⇒
#    两道阈值全部走空 ⇒ **exit 0, 静默判健康**。失败方向朝着"没事", 这是最坏的一种。
#    🔨 判据(我在册且今天又犯): **判据要实现【这东西的定义】, 不是【它通常长什么样】。**
#       "数字和连字符" 是整数的**外观**; 整数的**定义**是: 可选一个前导负号 + 一位以上数字, 再无别的。
#    🔨 另一条: **变异测试证不了这个洞** —— 它只检验用例守不守得住现有代码路径,
#       判据本身太窄, 得靠有人拿新输入去打。绿 + 变异全检出, 仍然漏了它。
n=$HB
case "$n" in -*) n=${n#-} ;; esac   # 只剥【一个】前导负号; `--5` 剥完剩 `-5`, 下一步会拦下
case "$n" in
  ''|*[!0-9]*)
    echo "🔴 进程在但【心跳不可用】(HB=${HB:-空}) — 进程在不等于循环在转"
    exit 1
    ;;
esac

if [ "$HB" -gt "$HB_MAX" ]; then
  echo "🔴 进程在但【心跳陈旧】: ${HB}ms > ${HB_MAX}ms — 循环可能卡死, 而进程数看起来一切正常"
  exit 1
fi
if [ "$HB" -lt "$HB_MIN" ]; then
  echo "🔴 心跳来自【未来】: ${HB}ms < ${HB_MIN}ms — 时钟跳变/状态文件被搬动, 这个读数不可信"
  exit 1
fi

# 心跳都过了, 最后才结算矿机那一格(刹车中则 miner_msg 为空 ⇒ 静默)
if [ -n "$miner_msg" ]; then
  echo "$miner_msg"
  exit 1
fi
exit 0
