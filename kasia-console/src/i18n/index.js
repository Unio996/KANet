export function parseLang(cookieHeader = '') {
  const m = (cookieHeader || '').match(/kanet_lang=([a-z]{2})/);
  const l = m?.[1];
  return (l && T[l]) ? l : 'zh';
}

export function isRtl(lang) { return RTL.has(lang); }
export function getT(lang) {
  const base = T.zh;
  const en = T.en;
  const target = T[lang];
  if (!target || lang === 'zh') return base;
  if (lang === 'en') return { ...base, ...en };
  return { ...base, ...en, ...target };
}
